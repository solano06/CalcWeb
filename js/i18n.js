export function localizeStepsResult(solution, lang = "es") {
  if (!solution || !solution.ok || lang === "es" || !Array.isArray(solution.steps)) {
    return solution;
  }

  const phraseMap = lang === "en" ? STEP_PHRASE_MAP_EN : STEP_PHRASE_MAP_FR;

  const translateText = (txt) => {
    let out = txt;
    for (const [esPhrase, targetPhrase] of phraseMap) {
      if (out.includes(esPhrase)) {
        out = out.replace(esPhrase, targetPhrase);
      }
    }
    return out;
  };

  return {
    ...solution,
    steps: solution.steps.map((st) => ({
      titulo_paso: translateText(st.titulo_paso),
      explicacion: translateText(st.explicacion),
      latex: st.latex
    }))
  };
}

